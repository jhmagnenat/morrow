import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {mkdtempSync,mkdirSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {applyCurriculum} from './apply-insurance-curriculum.mjs';
import {curriculum,excluded} from './insurance-curriculum-v17.mjs';
import {DOCUMENT} from './repair-understand-content.mjs';

mkdirSync('.next',{recursive:true});
const workspace=mkdtempSync(resolve('.next/curriculum-test-'));
const databasePath=resolve(workspace,'fixture.db'),pdfPath=resolve(workspace,'fixture.pdf');
writeFileSync(pdfPath,'Isolated migration fixture: never a production PDF.');
const expectedPdfSha256=createHash('sha256').update('Isolated migration fixture: never a production PDF.').digest('hex');
const options={databasePath,pdfPath,expectedPdfSha256,backupDirectory:resolve(workspace,'backups')};
const db=new DatabaseSync(databasePath);
db.exec(`
CREATE TABLE notions(id TEXT PRIMARY KEY,label TEXT,domain TEXT,status TEXT,definition TEXT,explanation TEXT,grounding TEXT,work_questions TEXT,course_context TEXT,mapping_visible INTEGER);
CREATE TABLE notion_metadata(notion_id TEXT PRIMARY KEY,layer TEXT,evidence TEXT,user_edited INTEGER,generation_version TEXT,source_notes TEXT,clair TEXT);
CREATE TABLE notion_sources(notion_id TEXT,document_id TEXT,page INTEGER);
CREATE TABLE links(id TEXT PRIMARY KEY,source_id TEXT,target_id TEXT,type TEXT,description TEXT);
CREATE TABLE link_metadata(link_id TEXT PRIMARY KEY,evidence TEXT);
CREATE TABLE study_cards(id TEXT PRIMARY KEY,card_type TEXT,notion_id TEXT,link_id TEXT,payload TEXT);
CREATE TABLE passages(document_id TEXT,page INTEGER,ordinal INTEGER,text TEXT,generated INTEGER);
CREATE TABLE documents(id TEXT PRIMARY KEY);
CREATE TABLE quality_settings(key TEXT PRIMARY KEY,value TEXT);
CREATE TABLE page_analysis(document_id TEXT,page INTEGER,payload TEXT,PRIMARY KEY(document_id,page));
CREATE TABLE review_state(card_id TEXT,state TEXT);
CREATE TABLE review_log(card_id TEXT,grade TEXT);
CREATE TABLE mastery_signals(id TEXT,payload TEXT);
CREATE TABLE review_requests(id TEXT,payload TEXT);
CREATE TABLE interview_sessions(id TEXT,payload TEXT);
CREATE TABLE explain_attempts(id TEXT,payload TEXT);
`);
db.prepare('INSERT INTO documents VALUES(?)').run(DOCUMENT);
for(let page=1;page<=38;page++)db.prepare('INSERT INTO passages VALUES(?,?,?,?,0)').run(DOCUMENT,page,0,`Original source fixture page ${page}, preserved as an exact textual quotation.`);
const first=curriculum[0];
db.prepare('INSERT INTO notions VALUES(?,?,?,?,?,?,?,?,?,?)').run('existing',first.label,'old','draft','Old definition','Old explanation','inferred','[]','',1);
db.prepare('INSERT INTO notion_metadata VALUES(?,?,?,?,?,?,?)').run('existing','course','[]',0,'old','[]',null);
db.prepare('INSERT INTO notion_sources VALUES(?,?,?)').run('existing',DOCUMENT,first.pages[0]);
db.prepare('INSERT INTO study_cards VALUES(?,?,?,?,?)').run('existing','notion','existing',null,JSON.stringify({id:'existing',notionId:'existing',cardType:'notion',question:'Old question',answer:'Old answer',status:'ready'}));
db.prepare('INSERT INTO review_state VALUES(?,?)').run('existing','Existing FSRS state');
db.prepare('INSERT INTO review_log VALUES(?,?)').run('existing','good');
const archivedLabel=Object.keys(excluded)[0];
db.prepare('INSERT INTO notions VALUES(?,?,?,?,?,?,?,?,?,?)').run('archive',archivedLabel,'old','draft','Old advertising','Old advertising','inferred','[]','',1);
db.prepare('INSERT INTO notion_sources VALUES(?,?,?)').run('archive',DOCUMENT,24);
db.prepare('INSERT INTO links VALUES(?,?,?,?,?)').run('old-edge','existing','archive','related','Obsolete connection');
const snapshot=()=>JSON.stringify(db.prepare('SELECT * FROM notions ORDER BY id').all());
const before=snapshot(),previousDirectory=process.env.MORROW_DATA_DIR;
assert.equal((await applyCurriculum(options)).concepts,48);
assert.equal(process.env.MORROW_DATA_DIR,previousDirectory,'Migration helpers must not redirect the caller database');
assert.equal(snapshot(),before,'Preview is read-only');
await assert.rejects(applyCurriculum({...options,expectedPdfSha256:'wrong',dryRun:false}),/PDF was replaced/);
assert.equal(snapshot(),before,'Wrong PDF cannot modify content');
db.prepare('DELETE FROM passages WHERE page=19').run();
await assert.rejects(applyCurriculum({...options,dryRun:false}),/Missing original page 19/);
assert.equal(snapshot(),before,'Missing source cannot cause a partial migration');
db.prepare('INSERT INTO passages VALUES(?,?,?,?,0)').run(DOCUMENT,19,0,'Original source fixture page 19, preserved as an exact textual quotation.');
const result=await applyCurriculum({...options,dryRun:false});
assert.equal(result.report.readyCards,144);
assert.equal(result.report.readyCardsWithIssues,0);
assert.equal(result.historyPreserved,true);
assert.equal(db.prepare('SELECT state FROM review_state').get().state,'Existing FSRS state');
assert.equal(db.prepare('SELECT grade FROM review_log').get().grade,'good');
assert.equal(db.prepare('SELECT mapping_visible FROM notions WHERE id=?').get('archive').mapping_visible,0);
assert(db.prepare('SELECT id FROM links WHERE id=?').get('old-edge'),'Original edges stay recoverable');
const backup=new DatabaseSync(result.backup,{readOnly:true});
assert.equal(JSON.stringify(backup.prepare('SELECT * FROM notions ORDER BY id').all()),before);backup.close();
const ids=JSON.stringify(db.prepare('SELECT id FROM study_cards ORDER BY id').all());
const repeat=await applyCurriculum({...options,dryRun:false});
assert.equal(repeat.createdCards,0);assert.equal(repeat.created,0);
assert.equal(JSON.stringify(db.prepare('SELECT id FROM study_cards ORDER BY id').all()),ids);
db.prepare('UPDATE notion_metadata SET user_edited=1 WHERE notion_id=?').run('existing');
db.prepare('UPDATE notions SET definition=? WHERE id=?').run('My manually edited definition','existing');
await applyCurriculum({...options,dryRun:false});
assert.equal(db.prepare('SELECT definition FROM notions WHERE id=?').get('existing').definition,'My manually edited definition');
assert.equal(JSON.stringify(db.prepare('SELECT id FROM study_cards ORDER BY id').all()),ids);
db.close();
console.log('PASS: full curriculum transaction, PDF/source guards, read-only preview, recoverable backup, 144 checked cards, stable IDs, repeat safety, manual-edit protection and existing FSRS history. No model calls.');
