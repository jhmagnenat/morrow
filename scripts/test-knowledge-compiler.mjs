import assert from 'node:assert/strict';
import {isolatedModules} from './isolated-modules.mjs';
const env=await isolatedModules(['knowledgeCompiler']);
const {compileSourceKnowledge,knowledgeTaskIssues}=await env.load('knowledgeCompiler');
const {verifiesQuote}=await env.load('contentQuality');
const catalog=[{id:'a',page:1,text:'Pressure is 12 kPa when volume is fixed.'},{id:'b',page:2,text:'Pressure is 12 kPa when volume is fixed.'}];
const unit=(sources=['a'],extra={})=>({concept:'pressure',claim:'Pressure is 12 kPa.',kind:'fact',conditions:['Volume is fixed.'],sources:sources.map(sourceId=>({sourceId})),...extra});
const merged=compileSourceKnowledge([unit(),unit(['b'])],['pressure'],catalog,[1,2]);
assert.equal(merged.units.length,1);assert.deepEqual(merged.units[0].sourceIds,['a','b']);
assert.deepEqual(merged.units[0].pages,[1,2]);
const conditions=compileSourceKnowledge([unit(['a'],{conditions:['a','b']}),unit(['a'],{conditions:['b','a']})],['pressure'],catalog,[1]);
assert.equal(conditions.units.length,1,'Condition ordering does not duplicate a knowledge unit');
const bad=compileSourceKnowledge([unit(['missing']),unit(['b']),unit(['a'],{concept:'missing'})],['pressure'],catalog,[1]);
assert.equal(bad.units.length,0);assert.equal(bad.rejected.length,3);
const balanced=compileSourceKnowledge([...Array.from({length:10},(_,i)=>unit(['a'],{claim:'Page one objective '+i})),...Array.from({length:8},(_,i)=>unit(['b'],{claim:'Page two objective '+i}))],['pressure'],catalog,[1,2],8);
assert.equal(balanced.selectedIds.length,8);assert.equal(balanced.omittedIds.length,10);
assert.deepEqual(balanced.units.filter(u=>balanced.selectedIds.includes(u.id)).reduce((counts,u)=>{counts[u.pages[0]]=(counts[u.pages[0]]??0)+1;return counts;},{}),{1:4,2:4});
const task={knowledgeId:merged.units[0].id,concept:'pressure',kind:'definition',sources:[{sourceId:'b'}]};
assert.deepEqual(knowledgeTaskIssues(task,merged),[]);
assert(knowledgeTaskIssues({...task,kind:'mechanism'},merged).length,'A fact cannot become an invented mechanism');
assert(knowledgeTaskIssues({...task,sources:[{sourceId:'missing'}]},merged).length);
assert(knowledgeTaskIssues({...task,knowledgeId:'unknown'},merged).length);
assert(!verifiesQuote('The formula is x2 = 4.','The formula is x\u00b2 = 4.'));
assert(!verifiesQuote('The current is 12 pa.','The current is 12 pA.'));
assert(verifiesQuote('Pressure = 12 kPa.','Pressure\n=\u00a012  kPa.'));
console.log('PASS: merged evidence, canonical conditions, rejected provenance, balanced selection, typed task lineage and scientific quotation integrity. No API calls or pedagogical score.');
