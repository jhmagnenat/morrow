import assert from 'node:assert/strict';
import {isolatedModules} from './isolated-modules.mjs';
const env=await isolatedModules(['mappingKeyboard']);
const {mappingKeyboardTarget:next}=await env.load('mappingKeyboard');
const ids=Array.from({length:18},(_,i)=>String(i));
assert.equal(next([],null,'ArrowDown',3),undefined);
assert.equal(next(ids,null,'ArrowRight',4),'0');
assert.equal(next(ids,'invisible-parent','ArrowDown',4),'0');
assert.equal(next(ids,'0','ArrowRight',4),'1');
assert.equal(next(ids,'1','ArrowDown',4),'5');
assert.equal(next(ids,'5','ArrowUp',4),'1');
assert.equal(next(ids,'1','ArrowLeft',4),'0');
assert.equal(next(ids,'0','ArrowUp',4),undefined);
assert.equal(next(ids,'0','ArrowLeft',4),undefined);
assert.equal(next(ids,'15','ArrowRight',4),'16','Pagination follows the same ordered list');
assert.equal(next(ids,'15','ArrowDown',4),'17','An incomplete final row selects the closest remaining cell');
assert.equal(next(ids,'17','ArrowRight',4),undefined);
let cursor='0';for(let i=0;i<10;i++)cursor=next(ids,cursor,'ArrowRight',4);
assert.equal(cursor,'10','Repeated key events advance rather than reusing stale selection');
assert.equal(next(ids,'2','Enter',4),undefined,'Enter belongs to opening a branch, not directional movement');
console.log('PASS: visible-grid arrows, missing selection, repeated keys, pagination and incomplete rows.');
